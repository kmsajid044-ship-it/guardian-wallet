#!/usr/bin/env bash
# Hosted online demo entry point (container only; DEMO_PUBLIC=1). Builds and starts a fresh
# four-node FISCO BCOS network on 127.0.0.1 inside this container (or local Anvil when
# CHAIN_BACKEND=evm-local), deploys and seeds GuardianWallet and DemoLedger, then runs the gateway
# on port 7860. Test-only keys are generated here at every start and are never printed.
# Research prototype: USD and CNY demo balances on a simulated ledger, no real money.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"
export CHAIN_BACKEND="${CHAIN_BACKEND:-fisco}"
export DEMO_PUBLIC=1
fisco_version="v3.16.4"
# Container defaults; a local test of this script can move every port off the developer's own chain.
web3_port="${HOSTED_WEB3_PORT:-8545}"; p2p_port="${HOSTED_P2P_PORT:-30300}"; rpc_port="${HOSTED_RPC_PORT:-20200}"
agent_port="${AGENT_PORT:-8787}"; risk_port="${RISK_INTEL_PORT:-8788}"
rpc_url="http://127.0.0.1:$web3_port"
log() { printf '[start] %s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }

case "$CHAIN_BACKEND" in
  fisco) chain_id=1337; manifest="./deployments/fisco.json" ;;
  evm-local) chain_id=31337; manifest="./deployments/local.json" ;;
  *) echo "CHAIN_BACKEND must be fisco or evm-local" >&2; exit 1 ;;
esac

# Fresh test-only identities for this container run. The file is mode 0600 and never leaves the
# container; the language-model key stays in the process environment (Space secret) only.
umask 077
new_wallet() { cast wallet new --json | jq -r '(.data // .)[0] | "\(.address) \(.private_key)"'; }
read -r owner_address owner_key <<<"$(new_wallet)"
read -r agent_address agent_key <<<"$(new_wallet)"
contact() { new_wallet | cut -d' ' -f1; }
cat >"$repo_root/.env" <<ENV
# Generated by hosted/start.sh for this container run only. Synthetic test identities; no real money.
CHAIN_BACKEND=$CHAIN_BACKEND
RPC_URL=$rpc_url
FISCO_RPC_URL=$rpc_url
CHAIN_ID=$chain_id
DEPLOYMENTS_FILE=$manifest
OWNER_PRIVATE_KEY=$owner_key
AGENT_PRIVATE_KEY=$agent_key
AGENT_ADDRESS=$agent_address
GUARDIAN_ADDRESS=0x0000000000000000000000000000000000000000
FEE_ACCOUNT_ADDRESS=0x00000000000000000000000000000000000000f3
DEMO_CONTACT_1_ADDRESS=$(contact)
DEMO_CONTACT_2_ADDRESS=$(contact)
DEMO_CONTACT_3_ADDRESS=$(contact)
AGENT_PORT=$agent_port
RISK_INTEL_PORT=$risk_port
AUDIT_DB_PATH=./.demo/audit.sqlite
OWNER_SESSION_FILE=./.demo/owner-session
OWNER_TIMEZONE=UTC
OWNER_ACTIVE_HOURS=00-24
ENV
unset owner_key agent_key
umask 022
mkdir -p "$repo_root/.demo"
log "owner $owner_address, agent $agent_address (fresh test-only identities)"

if [[ "$CHAIN_BACKEND" == fisco ]]; then
  # shellcheck disable=SC1091
  source "$repo_root/scripts/lib/fisco-nodes.sh"
  runtime="$repo_root/.fisco"
  rm -rf "$runtime/nodes" "$runtime"/nodes.*
  log "building a fresh four-node FISCO BCOS $fisco_version network on 127.0.0.1"
  (cd "$runtime" && bash ./build_chain.sh -l 127.0.0.1:4 -p "$p2p_port,$rpc_port" -o "$runtime/nodes" -v "$fisco_version" -I 1337 -a "$owner_address" -e "$runtime/bin/fisco-bcos") >"$repo_root/.demo/build_chain.log" 2>&1 \
    || { tail -40 "$repo_root/.demo/build_chain.log" >&2; exit 1; }
  configure_fisco_nodes "$runtime/nodes/127.0.0.1" "$web3_port"
  # The Java SDK console talks to the first node's RPC port with this network's SDK certificates.
  if [[ ! -f "$runtime/console/conf/config.toml" ]]; then cp "$runtime/console/conf/config-example.toml" "$runtime/console/conf/config.toml"; fi
  perl -pi -e "s/^peers=.*/peers=[\"127.0.0.1:$rpc_port\",\"127.0.0.1:$((rpc_port + 1))\"]/" "$runtime/console/conf/config.toml"
  bash "$runtime/nodes/127.0.0.1/start_all.sh"
  if ! wait_for_nodes "$web3_port" 180; then
    echo "FISCO BCOS did not become ready" >&2
    tail -n 40 "$runtime"/nodes/127.0.0.1/node0/log/*.log >&2 || true
    exit 1
  fi
  node_version="$("$runtime/bin/fisco-bcos" --version | head -1)"
  export CHAIN_NODE_VERSION="$node_version"
  log "FISCO BCOS ready: $node_version; chain ID $(cast chain-id --rpc-url "$rpc_url"); four Web3 endpoints from $rpc_url"
else
  anvil --host 127.0.0.1 --port "$web3_port" --chain-id 31337 --silent >"$repo_root/.demo/anvil.log" 2>&1 &
  for _ in {1..60}; do cast chain-id --rpc-url "$rpc_url" >/dev/null 2>&1 && break; sleep 0.5; done
  export CHAIN_NODE_VERSION="$(anvil --version | head -1)"
  log "private EVM development chain (Anvil) ready: $CHAIN_NODE_VERSION; chain ID $(cast chain-id --rpc-url "$rpc_url")"
fi

log "deploying and seeding GuardianWallet and DemoLedger from config/currencies.json"
bash "$repo_root/hosted/deploy.sh"

export RPC_URL="$rpc_url" CHAIN_ID="$chain_id" AGENT_PORT="$agent_port" RISK_INTEL_PORT="$risk_port" DEPLOYMENTS_FILE="$manifest" OWNER_SESSION_FILE=./.demo/owner-session AUDIT_DB_PATH=./.demo/audit.sqlite
export LLM_PROVIDER="${LLM_PROVIDER:-mock}" LLM_HOURLY_CAP="${LLM_HOURLY_CAP:-60}"
if [[ "$LLM_PROVIDER" == groq && -z "${GROQ_API_KEY:-}" ]]; then
  log "LLM_PROVIDER=groq but no GROQ_API_KEY secret is set; the offline rules answer"
fi
log "AI proposer: $LLM_PROVIDER (hourly model-call cap $LLM_HOURLY_CAP, then offline rules)"
exec "$repo_root/agent/node_modules/.bin/tsx" "$repo_root/agent/src/hosted/main.ts"
