import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, readFileSync, rmSync } from "node:fs";
import { createServer } from "node:http";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { createGatewayHandler, IdleTracker, RateLimiter, type DemoInfo, type GatewayStatus } from "./gateway.js";

// Hosted online demo supervisor (DEMO_PUBLIC=1, inside the demo container only). It serves the
// gateway on the public port, runs Risk Intel and the agent on loopback, and resets the demo to a
// fresh deployment on request or after a quiet period. Keys are generated by hosted/start.sh into
// the container's .env and are never printed. Research prototype; USD and CNY demo units, no real money.

const repoRoot = fileURLToPath(new URL("../../../", import.meta.url));
const Env = z.object({
  DEMO_PUBLIC: z.literal("1"),
  PORT: z.coerce.number().int().positive().default(7860),
  CHAIN_BACKEND: z.enum(["fisco", "evm-local"]),
  AGENT_PORT: z.coerce.number().int().positive().default(8787),
  RISK_INTEL_PORT: z.coerce.number().int().positive().default(8788),
  DEPLOYMENTS_FILE: z.string().min(1),
  OWNER_SESSION_FILE: z.string().min(1),
  AUDIT_DB_PATH: z.string().min(1),
  WEB_DIST: z.string().min(1).default(resolve(repoRoot, "web/dist")),
  RESET_SCRIPT: z.string().min(1).default(resolve(repoRoot, "hosted/deploy.sh")),
  IDLE_RESET_MINUTES: z.coerce.number().positive().default(30),
  CHAT_LIMIT_PER_MINUTE: z.coerce.number().int().positive().default(20),
  LLM_HOURLY_CAP: z.coerce.number().int().positive().optional(),
  CHAIN_NODE_VERSION: z.string().optional(),
});
const env = Env.parse(process.env);
const at = (path: string) => resolve(repoRoot, path);
const tsx = at("agent/node_modules/.bin/tsx");

let status: GatewayStatus = "starting";
let children: ChildProcess[] = [];
let stopping = false;
const startedAt = new Date().toISOString();
const idle = new IdleTracker(env.IDLE_RESET_MINUTES * 60_000);
const log = (message: string) => console.log(`[hosted] ${new Date().toISOString()} ${message}`);

function info(): DemoInfo {
  let chainId = env.CHAIN_BACKEND === "fisco" ? 1337 : 31337;
  try { chainId = (JSON.parse(readFileSync(at(env.DEPLOYMENTS_FILE), "utf8")) as { chainId: number }).chainId; } catch { /* not deployed yet */ }
  return {
    backend: env.CHAIN_BACKEND,
    chainId,
    chainLabel: env.CHAIN_BACKEND === "fisco" ? "FISCO BCOS · online demo" : "private EVM development chain (Anvil)",
    nodeVersion: env.CHAIN_NODE_VERSION ?? null,
    startedAt,
  };
}

function startServices(): void {
  stopping = false;
  rmSync(at(env.OWNER_SESSION_FILE), { force: true });
  const childEnv = { ...process.env, RISK_INTEL_URL: `http://127.0.0.1:${env.RISK_INTEL_PORT}` };
  children = [
    spawnService("risk-intel", at("risk-intel"), childEnv),
    spawnService("agent", at("agent"), childEnv),
  ];
}

function spawnService(name: string, cwd: string, childEnv: NodeJS.ProcessEnv): ChildProcess {
  const child = spawn(tsx, ["src/index.ts"], { cwd, env: childEnv, stdio: ["ignore", "inherit", "inherit"] });
  child.on("exit", (code, signal) => {
    if (stopping) return;
    log(`${name} exited (${code ?? signal}); restarting the services`);
    if (status === "ready") void restart();
  });
  return child;
}

async function stopServices(): Promise<void> {
  stopping = true;
  await Promise.all(children.map((child) => new Promise<void>((done) => {
    if (child.exitCode !== null || child.signalCode !== null) return done();
    const timer = setTimeout(() => { child.kill("SIGKILL"); }, 5_000);
    child.once("exit", () => { clearTimeout(timer); done(); });
    child.kill("SIGTERM");
  })));
  children = [];
}

async function waitHealthy(timeoutMs = 120_000): Promise<void> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const agentUp = await answers(`http://127.0.0.1:${env.AGENT_PORT}/health`);
    const riskUp = await answers(`http://127.0.0.1:${env.RISK_INTEL_PORT}/fx`);
    if (agentUp && riskUp && existsSync(at(env.OWNER_SESSION_FILE))) return;
    await sleep(1_000);
  }
  throw new Error("agent or Risk Intel did not become ready");
}

async function answers(url: string): Promise<boolean> {
  try { await fetch(url, { signal: AbortSignal.timeout(2_000) }); return true; } catch { return false; }
}

async function restart(): Promise<void> {
  status = "starting";
  await stopServices();
  startServices();
  try { await waitHealthy(); status = "ready"; } catch (error) { status = "failed"; log(String(error)); }
}

function runResetScript(): Promise<void> {
  return new Promise((done, fail) => {
    const child = spawn("bash", [env.RESET_SCRIPT], { cwd: repoRoot, env: process.env, stdio: ["ignore", "inherit", "inherit"] });
    child.on("exit", (code) => code === 0 ? done() : fail(new Error(`reset script exited with ${code}`)));
    child.on("error", fail);
  });
}

function requestReset(reason: string): { accepted: boolean; message: string } {
  if (status === "resetting" || status === "starting") return { accepted: false, message: "A reset is already in progress." };
  void reset(reason);
  return { accepted: true, message: "Resetting the demo: fresh contracts and synthetic seed data on the running chain. This takes about a minute." };
}

async function reset(reason: string): Promise<void> {
  status = "resetting";
  const started = Date.now();
  log(`reset started (${reason})`);
  await stopServices();
  for (let attempt = 1; attempt <= 2; attempt++) {
    try {
      await runResetScript();
      // A clean Activity list for the next visitor: the audit log belongs to the old deployment.
      for (const suffix of ["", "-wal", "-shm"]) rmSync(at(env.AUDIT_DB_PATH) + suffix, { force: true });
      startServices();
      await waitHealthy();
      idle.clear();
      status = "ready";
      log(`reset finished in ${Math.round((Date.now() - started) / 1_000)} s`);
      return;
    } catch (error) {
      log(`reset attempt ${attempt} failed: ${String(error)}`);
      await stopServices();
    }
  }
  status = "failed";
}

const server = createServer(createGatewayHandler({
  agentUrl: `http://127.0.0.1:${env.AGENT_PORT}`,
  webDist: env.WEB_DIST,
  deploymentFile: at(env.DEPLOYMENTS_FILE),
  readOwnerToken: () => readFileSync(at(env.OWNER_SESSION_FILE), "utf8"),
  info,
  status: () => status,
  requestReset,
  chatLimiter: new RateLimiter(env.CHAT_LIMIT_PER_MINUTE),
  chatLimitPerMinute: env.CHAT_LIMIT_PER_MINUTE,
  idle,
  idleResetMinutes: env.IDLE_RESET_MINUTES,
  llmHourlyCap: env.LLM_HOURLY_CAP ?? null,
}));

setInterval(() => { if (status === "ready" && idle.due()) requestReset(`idle for ${env.IDLE_RESET_MINUTES} min`); }, 60_000).unref();
for (const signal of ["SIGTERM", "SIGINT"] as const) {
  process.on(signal, () => { void stopServices().then(() => process.exit(0)); });
}

server.listen(env.PORT, "0.0.0.0", () => log(`gateway listening on port ${env.PORT}; chain ${info().chainLabel}, chain ID ${info().chainId}`));
startServices();
waitHealthy().then(() => { status = "ready"; log("agent and Risk Intel ready"); }, (error) => { status = "failed"; log(String(error)); });

function sleep(ms: number): Promise<void> { return new Promise((done) => setTimeout(done, ms)); }
