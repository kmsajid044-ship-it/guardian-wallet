// Generates docs/LICENSES.md from the installed dependency tree (`pnpm licenses list`) plus the
// non-npm components. Run with `pnpm licenses:doc` after changing dependencies.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const list = (args) => JSON.parse(execFileSync("pnpm", ["licenses", "list", "--json", "-r", ...args], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
const all = list([]);
const prod = list(["--prod"]);
const prodNames = new Set(Object.values(prod).flat().map((item) => item.name));
const packages = Object.entries(all).flatMap(([license, items]) => items.map((item) => ({ ...item, license })))
  .sort((left, right) => left.name.localeCompare(right.name));
const byName = new Map(packages.map((item) => [item.name, item]));

const workspaces = ["contracts", "agent", "risk-intel", "web", "eval", "."];
const direct = workspaces.flatMap((workspace) => {
  const manifest = JSON.parse(readFileSync(resolve(root, workspace, "package.json"), "utf8"));
  const label = workspace === "." ? "root" : workspace;
  return [
    ...Object.keys(manifest.dependencies ?? {}).map((name) => ({ workspace: label, name, scope: "runtime" })),
    ...Object.keys(manifest.devDependencies ?? {}).map((name) => ({ workspace: label, name, scope: "development" })),
  ];
});

const command = (file, args) => { try { return execFileSync(file, args, { encoding: "utf8" }).split("\n")[0].trim(); } catch { return "not installed"; } };
const forgeStd = JSON.parse(readFileSync(resolve(root, "contracts/lib/forge-std/package.json"), "utf8")).version;
const fiscoBinary = resolve(root, ".fisco/nodes/127.0.0.1/fisco-bcos");
const fiscoVersion = existsSync(fiscoBinary) ? command(fiscoBinary, ["--version"]).replace(/^FISCO BCOS Version : /, "") : "3.16.4 (pinned in scripts/chain-up.sh)";
const consoleVersion = /fisco_console_version="([^"]+)"/.exec(readFileSync(resolve(root, "scripts/lib/fisco-console.sh"), "utf8"))?.[1] ?? "unknown";
const forgeVersion = command(resolve(process.env.HOME ?? "", ".foundry/bin/forge"), ["--version"]).replace(/^forge Version: /, "");

const counts = Object.entries(all).map(([license, items]) => [license, items.length, items.filter((item) => prodNames.has(item.name)).length]).sort((left, right) => right[1] - left[1]);
function copyleftLine() {
  const strong = packages.filter((item) => /(^|[^L])GPL|AGPL|LGPL/.test(item.license));
  const weak = packages.filter((item) => /MPL|EPL|CDDL/.test(item.license));
  const describe = (items) => items.map((item) => `\`${item.name}\` (${item.license}${prodNames.has(item.name) ? ", runtime" : ", build or development only"})`).join(", ");
  return `- Copyleft licenses among npm packages: ${strong.length ? `strong: ${describe(strong)}` : "no strong copyleft (GPL, LGPL, AGPL)"}; ${weak.length ? `weak (file-level): ${describe(weak)}` : "no weak copyleft"}.`;
}

const cell = (value) => String(value).replaceAll("|", "\\|");
const lines = [
  "# Licenses",
  "",
  "Guardian Wallet is released under the MIT License (`LICENSE`). This file lists every third-party component it uses. It is generated by `pnpm licenses:doc` from the installed dependency tree, so versions and licenses are the ones actually resolved by `pnpm-lock.yaml`.",
  "",
  `- npm packages: **${packages.length}** installed (direct and transitive), of which **${prodNames.size}** are runtime dependencies of a workspace; the rest are build, test, and lint tooling.`,
  copyleftLine(),
  "",
  "## Summary by license",
  "",
  "| License | Packages | Of which runtime |",
  "|---|---|---|",
  ...counts.map(([license, total, runtime]) => `| ${license} | ${total} | ${runtime} |`),
  "",
  "## Components outside npm",
  "",
  "| Component | Version | License | Use | Distribution |",
  "|---|---|---|---|---|",
  `| FISCO BCOS (\`fisco-bcos\`, \`build_chain.sh\`) | ${fiscoVersion} | Apache-2.0 | Local four-node permissioned chain | Downloaded by \`scripts/chain-up.sh\` from the official FISCO BCOS release; not committed |`,
  `| FISCO BCOS console and Java SDK | ${consoleVersion} | Apache-2.0 | Local bootstrap of execution balances | Downloaded on demand; not committed |`,
  `| forge-std | ${forgeStd} | MIT OR Apache-2.0 | Foundry test and script helpers | Vendored in \`contracts/lib/forge-std\` with its license files |`,
  `| Foundry (forge, cast, anvil) | ${forgeVersion} | MIT OR Apache-2.0 | Build, test, local development chain | Tool installed by the user; not redistributed |`,
  "| Solidity compiler (solc) | 0.8.24 | GPL-3.0 | Compiles the contracts | Build tool fetched by Foundry; not redistributed |",
  "| Java runtime | user-installed | The vendor's license | Runs the FISCO BCOS console | Installed by the user; not redistributed |",
  "",
  "## Direct dependencies",
  "",
  "| Workspace | Package | Version | License | Scope |",
  "|---|---|---|---|---|",
  ...direct.map((dep) => { const item = byName.get(dep.name); return `| ${dep.workspace} | ${dep.name} | ${item ? item.versions.join(", ") : "—"} | ${item ? cell(item.license) : "—"} | ${dep.scope} |`; }),
  "",
  "## All installed npm packages",
  "",
  "| Package | Version | License | Runtime |",
  "|---|---|---|---|",
  ...packages.map((item) => `| ${cell(item.name)} | ${item.versions.join(", ")} | ${cell(item.license)} | ${prodNames.has(item.name) ? "yes" : "—"} |`),
  "",
];
writeFileSync(resolve(root, "docs/LICENSES.md"), `${lines.join("\n")}\n`);
console.log(`Wrote docs/LICENSES.md: ${packages.length} npm packages (${prodNames.size} runtime) and ${6} other components`);
