// Attack Lab runner. Usage:
//   pnpm attacks                 run all eleven scenarios in-process on the local chain
//   pnpm attacks A2 A9           run selected scenarios
//   pnpm attacks --api           ask the running agent API (ATTACK_LAB_URL) to run them
// Writes docs/ATTACK_LAB_EVIDENCE.md and docs/attack-lab-results.json. Exits 1 unless every
// selected scenario is blocked. Research prototype: USD and CNY demo balances, no real money.
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { AttackLab } from "../agent/src/attack/attackLab.js";
import { attackIds, directProofIds, type AttackId, type AttackResult } from "../agent/src/attack/types.js";
import { AuditLog } from "../agent/src/audit/audit.js";
import { loadConfig, resolveRepoPath } from "../agent/src/config.js";
import { CNY_DISCLAIMER } from "../agent/src/currency/registry.js";

const repoRoot = fileURLToPath(new URL("../", import.meta.url));
const args = process.argv.slice(2);
const useApi = args.includes("--api");
const requested = args.filter((arg) => !arg.startsWith("--")).map((arg) => arg.toUpperCase());
const unknown = requested.filter((id) => !attackIds.includes(id as AttackId));
if (unknown.length > 0) throw new Error(`Unknown attack: ${unknown.join(", ")}. Choose from ${attackIds.join(", ")}.`);
const selected = (requested.length > 0 ? requested : [...attackIds]) as AttackId[];

const results = useApi ? await viaApi(selected) : await inProcess(selected);
const rows = results.map((result) => ({
  attack: `${result.id} ${result.title}`,
  status: result.status,
  blockedBy: result.blockedBy,
  hash: result.transactionHash ?? "—",
  directProof: result.directProof ? `${result.directProof.transactionHash} (${proofLabel(result.directProof.status)})` : directProofIds.includes(result.id) ? "MISSING" : "—",
}));
console.table(rows);
for (const result of results) console.log(`${result.id}: ${result.reason}`);

if (requested.length === 0) {
  writeFileSync(resolve(repoRoot, "docs/attack-lab-results.json"), `${JSON.stringify(results, null, 2)}\n`);
  writeFileSync(resolve(repoRoot, "docs/ATTACK_LAB_EVIDENCE.md"), evidenceMarkdown(results));
  console.log("Evidence written to docs/ATTACK_LAB_EVIDENCE.md and docs/attack-lab-results.json");
}

const failures = results.filter((result) => result.status !== "BLOCKED" || (directProofIds.includes(result.id) && !result.directProof));
if (failures.length > 0) {
  console.error(`Not blocked: ${failures.map((result) => result.id).join(", ")}`);
  process.exit(1);
}
console.log(`All ${results.length} selected scenarios were blocked on ${results[0]?.backend ?? "the local chain"}.`);

async function inProcess(ids: AttackId[]): Promise<AttackResult[]> {
  const config = loadConfig();
  const lab = new AttackLab(config, process.env, { audit: new AuditLog(resolveRepoPath(config.AUDIT_DB_PATH)) });
  const output: AttackResult[] = [];
  for (const id of ids) {
    process.stderr.write(`Running ${id} on ${config.CHAIN_BACKEND}…\n`);
    output.push(await lab.run(id));
  }
  return output;
}

async function viaApi(ids: AttackId[]): Promise<AttackResult[]> {
  const base = process.env.ATTACK_LAB_URL ?? "http://127.0.0.1:8787";
  const output: AttackResult[] = [];
  for (const id of ids) {
    const response = await fetch(`${base}/attack-lab/run/${id}`, { method: "POST", headers: { "content-type": "application/json" }, body: "{}" });
    if (!response.ok) throw new Error(`Attack Lab ${id} failed (${response.status}): ${await response.text()}`);
    output.push(await response.json() as AttackResult);
  }
  return output;
}

function proofLabel(status: string): string {
  return status === "reverted" ? "reverted" : "mined, contract returned BLOCKED";
}

function evidenceMarkdown(items: AttackResult[]): string {
  const cell = (value: string) => value.replaceAll("|", "\\|");
  const lines = [
    "# Attack Lab evidence",
    "",
    `Generated by \`pnpm attacks\` on ${new Date().toISOString()} against the local \`${items[0]?.backend ?? "unknown"}\` network (permissioned chain operated by the team).`,
    "Each scenario deploys its own GuardianWallet and DemoLedger, so shared demo balances are untouched. Research prototype with USD and CNY demo balances; no real money.",
    "",
    `> ${CNY_DISCLAIMER}`,
    "",
    "| Attack | Status | Blocked by | Reason | Pipeline / primary hash | Direct-to-contract proof |",
    "|---|---|---|---|---|---|",
    ...items.map((item) => `| ${item.id} ${cell(item.title)} | ${item.status} | ${item.blockedBy} | ${cell(item.reason)} | ${item.transactionHash ? `\`${item.transactionHash}\` (block ${item.blockNumber})${item.revertRecord ? `, revert ${cell(item.revertRecord)}` : ""}` : "off-chain refusal, no transaction"} | ${item.directProof ? `\`${item.directProof.transactionHash}\` (block ${item.directProof.blockNumber}, ${proofLabel(item.directProof.status)})` : "—"} |`),
    "",
    "## Step records",
    "",
    ...items.flatMap((item) => [
      `### ${item.id} ${item.title}`,
      "",
      item.description,
      "",
      ...item.steps.map((step) => `- **${step.layer}** ${step.outcome}: ${step.detail}${step.transactionHash ? ` — \`${step.transactionHash}\` (block ${step.blockNumber})` : ""}`),
      "",
    ]),
  ];
  return `${lines.join("\n")}\n`;
}
